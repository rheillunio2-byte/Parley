"""Small educational A2A-style JSON-RPC agent server (not full spec conformance)."""
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json, sys, uuid
from datetime import datetime, timezone

AGENTS = {
    "research": {
        "name": "Research Agent", "description": "Extracts key points from a user-provided topic.",
        "skill": {"id": "research_topic", "name": "Research topic", "description": "Creates a structured research brief from supplied text."}
    },
    "analysis": {
        "name": "Analysis Agent", "description": "Turns a research brief into actionable findings.",
        "skill": {"id": "analyze_brief", "name": "Analyze brief", "description": "Identifies themes, implications, and recommendations."}
    },
    "writer": {
        "name": "Report Agent", "description": "Creates a concise final report from analysis.",
        "skill": {"id": "write_report", "name": "Write report", "description": "Formats findings as a readable report artifact."}
    }
}

def execute(kind, text):
    text = str(text).strip()
    if not text:
        raise ValueError("The task text cannot be empty.")
    if kind == "research":
        sentences = [s.strip() for s in text.replace('\n', ' ').split('.') if s.strip()]
        bullets = sentences[:5] or [text]
        return "Research brief\n" + "\n".join(f"- {x.rstrip('.')}." for x in bullets) + f"\n\nSource input length: {len(text)} characters."
    if kind == "analysis":
        words = text.split()
        return ("Analysis\n"
                f"- Main subject: {words[0:8] and ' '.join(words[:8])}\n"
                f"- Key points identified: {min(5, max(1, text.count('- ')))}\n"
                "- Consideration: validate factual claims against authoritative sources.\n"
                "- Recommendation: convert the strongest points into specific, measurable next steps.\n\n"
                f"Working notes ({len(words)} words): {text[:700]}")
    if kind == "writer":
        return ("MULTI-AGENT REPORT\n\n"
                "Executive summary\nThe specialist agents processed the submitted topic in sequence and produced this report.\n\n"
                "Findings and analysis\n" + text + "\n\n"
                "Next steps\n1. Verify important claims using reliable sources.\n"
                "2. Assign an owner and deadline to each recommended action.\n"
                "3. Review the report before using it for decisions.\n\n"
                "Generated by the local A2A learning demo.")
    raise ValueError("Unknown agent.")

class Handler(BaseHTTPRequestHandler):
    kind = None
    def log_message(self, *_): pass
    def send_json(self, data, status=200):
        raw = json.dumps(data, ensure_ascii=False).encode()
        self.send_response(status); self.send_header('Content-Type','application/json; charset=utf-8')
        self.send_header('Content-Length', str(len(raw))); self.send_header('Access-Control-Allow-Origin','*')
        self.end_headers(); self.wfile.write(raw)
    def do_OPTIONS(self):
        self.send_response(204); self.send_header('Access-Control-Allow-Origin','*')
        self.send_header('Access-Control-Allow-Headers','Content-Type'); self.send_header('Access-Control-Allow-Methods','POST, GET, OPTIONS'); self.end_headers()
    def do_GET(self):
        if self.path == '/.well-known/agent-card.json':
            cfg = AGENTS[self.kind]
            port = self.server.server_port
            self.send_json({"name":cfg['name'],"description":cfg['description'],"url":f"http://127.0.0.1:{port}/rpc",
                "version":"1.0.0","protocolVersion":"1.0","preferredTransport":"JSONRPC",
                "capabilities":{"streaming":False,"pushNotifications":False},
                "defaultInputModes":["text/plain"],"defaultOutputModes":["text/plain"],"skills":[cfg['skill']]})
        elif self.path == '/health': self.send_json({"status":"ok","agent":AGENTS[self.kind]['name']})
        else: self.send_json({"error":"Not found"},404)
    def do_POST(self):
        if self.path != '/rpc': self.send_json({"error":"Not found"},404); return
        try:
            req=json.loads(self.rfile.read(int(self.headers.get('Content-Length','0'))))
            if req.get('jsonrpc') != '2.0' or req.get('method') != 'tasks/send': raise ValueError('Use JSON-RPC 2.0 method tasks/send.')
            params=req.get('params') or {}; message=params.get('message') or {}
            parts=message.get('parts') or []
            text=' '.join(str(p.get('text','')) for p in parts if p.get('type')=='text')
            result=execute(self.kind,text)
            task_id=params.get('id') or str(uuid.uuid4())
            payload={"id":task_id,"status":{"state":"completed","timestamp":datetime.now(timezone.utc).isoformat()},
                     "artifacts":[{"artifactId":str(uuid.uuid4()),"name":f"{self.kind}-result.txt","parts":[{"type":"text","text":result}]}]}
            self.send_json({"jsonrpc":"2.0","id":req.get('id'),"result":payload})
        except Exception as e:
            self.send_json({"jsonrpc":"2.0","id":None,"error":{"code":-32602,"message":str(e)}},400)

def main():
    if len(sys.argv)!=3 or sys.argv[1] not in AGENTS: raise SystemExit('Usage: python agents/server.py <research|analysis|writer> <port>')
    kind,port=sys.argv[1],int(sys.argv[2]); cls=type('AgentHandler',(Handler,),{'kind':kind})
    print(f"{AGENTS[kind]['name']} listening on http://127.0.0.1:{port}",flush=True)
    ThreadingHTTPServer(('127.0.0.1',port),cls).serve_forever()
if __name__=='__main__': main()
